export type SpriteName = keyof typeof SPRITES;

export function sprite(name: SpriteName, scale = 4, cls = ""): HTMLCanvasElement {
  const rows = SPRITES[name];
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const c = document.createElement("canvas");
  c.width = w;
  c.height = h;
  const ctx = c.getContext("2d")!;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === "#") ctx.fillStyle = "#000";
      else if (ch === ".") ctx.fillStyle = "#fff";
      else continue;
      ctx.fillRect(x, y, 1, 1);
    }
  });
  c.className = `sprite ${cls}`.trim();
  c.style.width = `${w * scale}px`;
  c.style.height = `${h * scale}px`;
  c.setAttribute("aria-hidden", "true");
  return c;
}

/** "[########--------]  52%" */
export function asciiBar(fraction: number, width = 20): string {
  const f = Math.max(0, Math.min(1, fraction));
  const n = Math.round(f * width);
  return `[${"#".repeat(n)}${"-".repeat(width - n)}] ${String(Math.floor(f * 100)).padStart(3, " ")}%`;
}

/** A strip of drifting bits between the two machines on the home screen. */
export function beam(width = 18): { el: HTMLElement; stop(): void } {
  const el = document.createElement("pre");
  el.className = "beam";
  let t = 0;
  const bits = Array.from({ length: 64 }, () => (Math.random() < 0.5 ? "0" : "1"));
  const draw = () => {
    t++;
    let s = "";
    for (let i = 0; i < width; i++) {
      const k = (i - t + 64 * 100) % 8;
      s += k === 0 ? ">" : bits[(i + t) % bits.length];
    }
    el.textContent = s;
  };
  draw();
  const timer = setInterval(draw, 140);
  return { el, stop: () => clearInterval(timer) };
}
